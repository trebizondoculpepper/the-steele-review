import { randomUUID } from "node:crypto";
import { z } from "zod";
import { CollectionRecordSchema, collectionArtifactPath } from "../collection/collection-store.js";
import { requestReingest } from "../collection/reingest.js";
import { sourceVersionFor } from "../content/fulltext-document.js";
import type { GitArtifactStore } from "../controllers/artifact-store.js";
import type { OperationStore } from "../controllers/operation-store.js";
import { escapeHtml, type DashboardView } from "./server.js";

/**
 * Console re-fetch of one captured source (#770).
 *
 * This is a thin action over the deliberate reingestion path (#558): it records
 * the same typed request and discovery event, and the running collector does
 * the fetch. Nothing is downloaded or written here, so there is no second
 * ingestion implementation to drift.
 *
 * The form carries a request id generated for that confirmation, so
 * resubmitting it attaches to the request it already made. A different request
 * while one is still in flight for the same post is deduplicated onto the open
 * one: the collector is allowed one reingestion per item at a time.
 */

/** Request identities generated by the console; the ingress pattern is a subset. */
const CONSOLE_REQUEST = /^console-refetch-[0-9a-f-]{36}$/;

const Selection = z
  .object({
    publication: z.string().regex(/^[a-z0-9][a-z0-9-]{0,199}$/),
    post: z.string().regex(/^[a-z0-9][a-z0-9-]{0,199}$/),
  })
  .strict();

/** The two selection fields, ignoring the action's own control fields. */
const selectionOf = (input: URLSearchParams) =>
  Selection.safeParse({
    publication: input.get("publication") ?? "",
    post: input.get("post") ?? "",
  });

export type RefetchState = "accepted" | "running" | "completed" | "failed";

/** Operator-facing status for one recorded reingestion request. */
export function refetchState(status: string): RefetchState {
  switch (status) {
    case "completed":
      return "completed";
    case "failed":
      return "failed";
    case "claimed":
      return "running";
    default:
      // Recorded but not yet claimed by the collector.
      return "accepted";
  }
}

export interface RefetchRequestSummary {
  requestId: string;
  state: RefetchState;
  /** True when the captured record already carries this request's version. */
  applied: boolean;
}

export interface RefetchDeps {
  archive: Pick<GitArtifactStore, "lookup" | "read">;
  operations: OperationStore;
}

const requestPrefix = (post: { publicationId: string; postId: string }) =>
  `reingest:substack/${post.publicationId}/${post.postId}/`;

const requestIdOf = (key: string) => key.slice(key.lastIndexOf("/") + 1);

async function capture(
  deps: Pick<RefetchDeps, "archive">,
  post: { publicationId: string; postId: string },
) {
  const ref = await deps.archive.lookup(collectionArtifactPath(post));
  if (!ref) return undefined;
  const record = CollectionRecordSchema.parse(JSON.parse(await deps.archive.read(ref)));
  if (record.item.publicationId !== post.publicationId || record.item.postId !== post.postId)
    return undefined;
  return { record, revision: sourceVersionFor(record.text), ref };
}

/** Reingestion requests recorded for one post. */
export function refetchRequests(
  deps: Pick<RefetchDeps, "operations">,
  post: { publicationId: string; postId: string },
  appliedRequestId?: string,
): RefetchRequestSummary[] {
  return deps.operations
    .listOperations(requestPrefix(post), 20)
    .map((status) => {
      const requestId = requestIdOf(status.key);
      return {
        requestId,
        state: refetchState(status.status),
        applied: requestId === appliedRequestId,
      };
    });
}

function rows(requests: readonly RefetchRequestSummary[]): string {
  if (requests.length === 0) return '<p class="empty">No re-fetch has been requested for this post.</p>';
  return `<div class="wrap"><table><thead><tr><th>Request</th><th>Status</th><th>Applied</th></tr></thead><tbody>${requests
    .map(
      (r) =>
        `<tr><td><code>${escapeHtml(r.requestId)}</code></td><td>${escapeHtml(r.state)}</td><td>${
          r.applied ? "Yes — this is the captured version" : "Not the current captured version"
        }</td></tr>`,
    )
    .join("")}</tbody></table></div>`;
}

/**
 * Confirm/status page. Without `request` it offers the action and shows recent
 * requests; with it, it shows that request's outcome and the exact captured
 * revision, so an operator can tell whether the re-fetch actually changed it.
 */
export function refetchView(deps: RefetchDeps): DashboardView {
  return {
    path: "/articles/refetch",
    title: "Re-fetch source",
    hidden: true,
    async render(url) {
      const parsed = selectionOf(url.searchParams);
      if (!parsed.success) return '<p class="empty">Choose an article from the list.</p>';
      const post = {
        publicationId: parsed.data.publication,
        postId: parsed.data.post,
      };
      const current = await capture(deps, post);
      if (!current)
        return `<p class="empty">No captured source is available for ${escapeHtml(
          post.publicationId,
        )}/${escapeHtml(post.postId)}. Re-fetch needs an existing capture.</p>`;

      const requested = url.searchParams.get("request") ?? "";
      const requestId = CONSOLE_REQUEST.test(requested) ? requested : undefined;
      const applied = current.record.reingestion?.requestId;
      const requests = refetchRequests(deps, post, applied);
      const label = `${post.publicationId}/${post.postId}`;

      const status = requestId
        ? (() => {
            const known = requests.find((r) => r.requestId === requestId);
            const state = known?.state;
            return `<h2>Re-fetch ${escapeHtml(requestId)}</h2><p>Status: <strong>${escapeHtml(
              state ?? "unknown",
            )}</strong>.${
              state === "completed"
                ? known?.applied
                  ? " The collector captured this request's version."
                  : " The request completed, but the capture does not carry this request's version; inspect the trace."
                : ""
            }${state === "failed" ? " The collector reported a failure; inspect the trace before retrying." : ""}</p>`;
          })()
        : "";

      const form = requestId
        ? ""
        : `<form method="post" action="/articles/refetch">
<input type="hidden" name="publication" value="${escapeHtml(post.publicationId)}">
<input type="hidden" name="post" value="${escapeHtml(post.postId)}">
<input type="hidden" name="request" value="console-refetch-${randomUUID()}">
<input type="hidden" name="confirm" value="yes">
<p>Re-fetching asks the running collector for fresh text and current provenance for this one post. An existing transcript is reused rather than paid for again, and the previous captured version stays readable at its commit. Repeated submissions of this form attach to the request they already made.</p>
<button>Re-fetch source</button></form>`;

      return `${status}<p>${escapeHtml(label)} is currently captured at <code>${escapeHtml(
        current.revision,
      )}</code>${
        applied ? ` by re-fetch <code>${escapeHtml(applied)}</code>` : ""
      }.</p>${form}<h2>Recent re-fetches</h2>${rows(requests)}<p><a href="/articles/trace?publication=${encodeURIComponent(
        post.publicationId,
      )}&post=${encodeURIComponent(post.postId)}">Back to the article trace</a></p>`;
    },
  };
}

export function refetchAction(deps: RefetchDeps) {
  return {
    async submit(form: URLSearchParams): Promise<{ status: number; location?: string }> {
      if (form.get("confirm") !== "yes") return { status: 400 };
      const parsed = selectionOf(form);
      const requested = form.get("request") ?? "";
      if (!parsed.success || !CONSOLE_REQUEST.test(requested)) return { status: 400 };
      const post = {
        publicationId: parsed.data.publication,
        postId: parsed.data.post,
      };
      const current = await capture(deps, post);
      if (!current) return { status: 409 };

      const location = (request: string) =>
        `/articles/refetch?publication=${encodeURIComponent(
          post.publicationId,
        )}&post=${encodeURIComponent(post.postId)}&request=${encodeURIComponent(request)}`;

      const outcome = requestReingest({
        operations: deps.operations,
        item: current.record.item,
        requestId: requested,
      });
      if (outcome.outcome === "conflicting-request") {
        // One reingestion per item at a time: attach the operator to the open
        // request instead of recording a second one.
        return { status: 303, location: location(requestIdOf(outcome.open)) };
      }
      return { status: 303, location: location(outcome.key.slice(outcome.key.lastIndexOf("/") + 1)) };
    },
  };
}

/** A re-fetch control for a post, using the same route as the action. */
export function refetchLink(origin: string, post: { publicationId: string; postId: string }) {
  return `${origin}/articles/refetch?publication=${encodeURIComponent(
    post.publicationId,
  )}&post=${encodeURIComponent(post.postId)}`;
}
